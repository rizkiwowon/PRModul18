public class PRModul13A {
    public static void main(String[] args) {

        // 1. Deklarasi variabel
        int a = 10;
        int b = 5;

        // 2. Operasi aritmatika
        int sum = a + b;
        int difference = a - b;
        int product = a * b;
        int quotient = a / b;
        int remainder = a % b;

        // Mencetak hasil
        System.out.println("a = " + a);
        System.out.println("b = " + b);
        System.out.println("Penjumlahan = " + sum);
        System.out.println("Pengurangan = " + difference);
        System.out.println("Perkalian = " + product);
        System.out.println("Pembagian = " + quotient);
        System.out.println("Sisa Bagi = " + remainder);
    }
}
