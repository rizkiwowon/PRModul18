public class PRModul13B {
    public static void main(String[] args) {

        // Deklarasi variabel
        int a = 10;

        // Operator penugasan
        a += 5;  // a = 15
        a -= 3;  // a = 12
        a *= 2;  // a = 24
        a /= 3;  // a = 8
        a %= 2;  // a = 0

        // Cetak nilai akhir
        System.out.println("Nilai akhir a = " + a);
    }
}
